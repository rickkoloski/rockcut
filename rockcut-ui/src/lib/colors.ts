// Department color palette + per-position shade derivation.
// A shift's fill = its department's base color, shifted in lightness by a
// deterministic step derived from the position ("shift type").

import type { Department } from './types'

const FALLBACK = '#6b7280' // neutral gray when a department has no color

export function departmentColor(dep?: Department | null): string {
  return dep?.color || FALLBACK
}

function hexToRgb(hex: string): [number, number, number] {
  const h = hex.replace('#', '')
  const full = h.length === 3 ? h.split('').map((c) => c + c).join('') : h
  const n = parseInt(full, 16)
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255]
}

function rgbToHex([r, g, b]: [number, number, number]): string {
  const c = (v: number) => Math.round(Math.max(0, Math.min(255, v))).toString(16).padStart(2, '0')
  return `#${c(r)}${c(g)}${c(b)}`
}

function rgbToHsl(r: number, g: number, b: number): [number, number, number] {
  r /= 255
  g /= 255
  b /= 255
  const max = Math.max(r, g, b)
  const min = Math.min(r, g, b)
  const d = max - min
  let h = 0
  if (d !== 0) {
    if (max === r) h = ((g - b) / d) % 6
    else if (max === g) h = (b - r) / d + 2
    else h = (r - g) / d + 4
    h *= 60
    if (h < 0) h += 360
  }
  const l = (max + min) / 2
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1))
  return [h, s, l]
}

function hslToRgb(h: number, s: number, l: number): [number, number, number] {
  const c = (1 - Math.abs(2 * l - 1)) * s
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1))
  const m = l - c / 2
  let r = 0
  let g = 0
  let b = 0
  if (h < 60) [r, g, b] = [c, x, 0]
  else if (h < 120) [r, g, b] = [x, c, 0]
  else if (h < 180) [r, g, b] = [0, c, x]
  else if (h < 240) [r, g, b] = [0, x, c]
  else if (h < 300) [r, g, b] = [x, 0, c]
  else [r, g, b] = [c, 0, x]
  return [(r + m) * 255, (g + m) * 255, (b + m) * 255]
}

export function contrastText(hex: string): '#000000' | '#ffffff' {
  const lin = (v: number) => {
    const c = v / 255
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4
  }
  const [r, g, b] = hexToRgb(hex)
  const L = 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b)
  return L > 0.5 ? '#000000' : '#ffffff'
}

const STEPS = [0, 0.12, -0.12, 0.24, -0.24, 0.06, -0.06]

/** Shade of a department base color for a given position. */
export function shiftColor(baseHex: string, positionId: number): { bg: string; fg: string } {
  const [h, s, l] = rgbToHsl(...hexToRgb(baseHex))
  const off = STEPS[Math.abs(positionId) % STEPS.length]
  const nl = Math.min(0.82, Math.max(0.24, l + off))
  const bg = rgbToHex(hslToRgb(h, s, nl))
  return { bg, fg: contrastText(bg) }
}
